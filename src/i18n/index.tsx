type Dict = typeof dict.en;
type DictKey = keyof Dict;

const I18nContext = React.createContext<{ lang: Lang; t: (k: DictKey) => string; setLang: (l: Lang) => void }>({
  lang: "en",
  t: (k) => dict.en[k],
  setLang: () => {},
});

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = React.useState<Lang>("en");
  React.useEffect(() => {
    const saved = typeof window !== "undefined" ? (localStorage.getItem("lang") as Lang | null) : null;
    if (saved === "en" || saved === "zh") setLangState(saved);
    else if (typeof navigator !== "undefined" && navigator.language?.toLowerCase().startsWith("zh")) setLangState("zh");
  }, []);
  const setLang = (l: Lang) => {
    setLangState(l);
    if (typeof window !== "undefined") localStorage.setItem("lang", l);
  };
  const t = React.useCallback((k: DictKey) => (dict[lang] as Dict)[k] ?? (dict.en as Dict)[k], [lang]);
  return <I18nContext.Provider value={{ lang, t, setLang }}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return React.useContext(I18nContext);
}
